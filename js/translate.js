// 2. ЛОГИКА ПЕРЕКЛЮЧЕНИЯ ЯЗЫКА
function changeLang(langCode) {
  // Проверяем, есть ли такой язык в словаре
  if (!translations[langCode]) return;

  // Переводим все обычные текстовые элементы
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[langCode][key]) {
      el.textContent = translations[langCode][key];
    }
  });

  // Переводим плейсхолдеры в инпутах
  const inputs = document.querySelectorAll('[data-i18n-placeholder]');
  inputs.forEach(input => {
    const key = input.getAttribute('data-i18n-placeholder');
    if (translations[langCode][key]) {
      input.placeholder = translations[langCode][key];
    }
  });

  // Обновляем плашку текущего языка в шапке
  const currentLangEl = document.querySelector('.lang-current');
  if (currentLangEl) {
    currentLangEl.textContent = langCode.toUpperCase();
  }

  // Сохраняем язык в память браузера
  localStorage.setItem('selectedLang', langCode);
  
  // Закрываем меню после выбора
  toggleLang();
}

// 3. ОТКРЫТИЕ / ЗАКРЫТИЕ ДРОПДАУНА
function toggleLang() {
  const dropdown = document.getElementById('lang-dropdown');
  if (dropdown) {
    dropdown.classList.toggle('show');
  }
}

// Закрытие дропдауна при клике в любое другое место экрана
window.onclick = function (event) {
  if (!event.target.matches('.lang-current')) {
    const dropdown = document.getElementById('lang-dropdown');
    if (dropdown && dropdown.classList.contains('show')) {
      dropdown.classList.remove('show');
    }
  }
};

// 4. ПРОВЕРКА СОХРАНЕННОГО ЯЗЫКА ПРИ ЗАГРУЗКЕ
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('selectedLang') || 'uk';
  changeLang(savedLang);
});